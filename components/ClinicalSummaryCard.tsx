import React, { useEffect, useState } from 'react';
import { BrainCircuit, Info } from 'lucide-react';
import { getClinicalSummary } from '../services/geminiService';

interface ClinicalSummaryCardProps {
  gene: string;
  variant: string;
}

/**
 * Tier 2: self-contained plain-English clinical summary card.
 * Fetches via getClinicalSummary (which never throws — it resolves to a
 * simulated string when offline/unavailable) and renders loading, error,
 * empty, and success states inside an mm-card-glowing wrapper.
 */
const ClinicalSummaryCard: React.FC<ClinicalSummaryCardProps> = ({ gene, variant }) => {
  const [summary, setSummary] = useState<string>('');
  const [source, setSource] = useState<string>('');
  const [loading, setLoading] = useState<boolean>(true);
  const [error, setError] = useState<boolean>(false);

  useEffect(() => {
    if (!gene || !variant) {
      setLoading(false);
      return;
    }

    let active = true;
    setLoading(true);
    setError(false);

    getClinicalSummary(gene, variant)
      .then((res) => {
        if (!active) return;
        setSummary(res.summary);
        setSource(res.source);
      })
      .catch(() => {
        if (active) setError(true);
      })
      .finally(() => {
        if (active) setLoading(false);
      });

    return () => {
      active = false;
    };
  }, [gene, variant]);

  return (
    <div className="mm-card-glowing mm-glow mm-glow--emerald p-6 relative overflow-hidden">
      <h3 className="text-white font-black text-sm uppercase tracking-wider mb-4 flex items-center gap-2.5">
        <div className="mm-section-accent" />
        <BrainCircuit className="h-4 w-4 text-emerald-400" />
        <span>Plain-English Clinical Summary</span>
        {source && (
          <span
            className={`text-[9px] uppercase tracking-wider font-extrabold px-2 py-0.5 rounded border ${
              source === 'SIMULATION'
                ? 'text-amber-300 border-amber-500/40 bg-amber-950/40'
                : 'text-emerald-300 border-emerald-500/40 bg-emerald-950/40'
            }`}
          >
            {source}
          </span>
        )}
      </h3>

      {loading && (
        <div className="space-y-3 animate-pulse" aria-hidden="true">
          <div className="h-3 bg-slate-800 rounded w-full"></div>
          <div className="h-3 bg-slate-800 rounded w-5/6"></div>
          <div className="h-3 bg-slate-800 rounded w-2/3"></div>
        </div>
      )}

      {!loading && error && (
        <p className="text-rose-300 text-sm">Unable to load the clinical summary. Please retry.</p>
      )}

      {!loading && !error && summary && (
        <p className="text-slate-200 leading-relaxed text-sm md:text-base">{summary}</p>
      )}

      {!loading && !error && !summary && (
        <p className="text-slate-400 text-sm italic">No clinical summary available for this variant.</p>
      )}

      <div className="mt-4 flex items-start gap-2 text-[11px] text-slate-400">
        <Info size={14} className="text-amber-400 shrink-0 mt-0.5" />
        <span>
          <strong className="text-amber-300 font-bold uppercase tracking-wide">Research Use Only:</strong>{' '}
          computational decision support generated by Gemini — not a diagnosis.
        </span>
      </div>
    </div>
  );
};

export default ClinicalSummaryCard;
