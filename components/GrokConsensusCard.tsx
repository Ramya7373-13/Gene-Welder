import React, { useEffect, useState } from 'react';
import { GitCompare, Info, ShieldCheck } from 'lucide-react';
import { getGrokValidation, GrokValidation } from '../services/grokService';

interface GrokConsensusCardProps {
  gene: string;
  variant: string;
}

const sourceBadgeClass = (source?: string): string => {
  if (source === 'SIMULATION' || source === 'FALLBACK') {
    return 'text-amber-300 border-amber-500/40 bg-amber-950/40';
  }
  return 'text-cyan-300 border-cyan-500/40 bg-cyan-950/40';
};

const FieldBlock: React.FC<{ label: string; value: string }> = ({ label, value }) => (
  <div className="rounded-lg border border-[color:var(--color-border)] bg-[color:var(--color-muted)]/60 p-3">
    <p className="text-[10px] font-extrabold uppercase tracking-widest text-cyan-400/90 mb-1.5">
      {label}
    </p>
    <p className="text-slate-200 leading-relaxed text-sm">{value}</p>
  </div>
);

/**
 * Independent Grok consensus panel. Fetches via getGrokValidation (never
 * throws — resolves to simulated JSON when offline/unavailable) and renders
 * validationSummary, structuralImpact, and consensusAssessment.
 */
const GrokConsensusCard: React.FC<GrokConsensusCardProps> = ({ gene, variant }) => {
  const [data, setData] = useState<GrokValidation | null>(null);
  const [loading, setLoading] = useState<boolean>(true);
  const [error, setError] = useState<boolean>(false);

  useEffect(() => {
    if (!gene || !variant) {
      setLoading(false);
      return;
    }

    let active = true;
    setLoading(true);
    setError(false);

    getGrokValidation(gene, variant)
      .then((res) => {
        if (!active) return;
        setData(res);
      })
      .catch(() => {
        if (active) setError(true);
      })
      .finally(() => {
        if (active) setLoading(false);
      });

    return () => {
      active = false;
    };
  }, [gene, variant]);

  const confidence =
    typeof data?.confidence === 'number' && Number.isFinite(data.confidence)
      ? Math.max(0, Math.min(100, data.confidence))
      : null;

  return (
    <div className="mm-card-glowing mm-glow mm-glow--cyan p-6 relative overflow-hidden border border-slate-800">
      <h3 className="text-white font-black text-sm uppercase tracking-wider mb-4 flex items-center gap-2.5 flex-wrap">
        <div className="mm-section-accent" />
        <ShieldCheck className="h-4 w-4 text-cyan-400" />
        <span>Grok Consensus Validation</span>
        {data?.source && (
          <span
            className={`text-[9px] uppercase tracking-wider font-extrabold px-2 py-0.5 rounded border ${sourceBadgeClass(data.source)}`}
          >
            {data.source}
          </span>
        )}
        {confidence !== null && (
          <span className="ml-auto text-[10px] font-mono font-extrabold text-cyan-300 border border-cyan-500/30 bg-cyan-950/40 px-2 py-0.5 rounded">
            {confidence.toFixed(0)}% conf
          </span>
        )}
      </h3>

      {loading && (
        <div className="space-y-3 animate-pulse" aria-hidden="true">
          <div className="h-16 bg-slate-800 rounded-lg w-full"></div>
          <div className="h-16 bg-slate-800 rounded-lg w-full"></div>
          <div className="h-16 bg-slate-800 rounded-lg w-5/6"></div>
        </div>
      )}

      {!loading && error && (
        <p className="text-rose-300 text-sm">Unable to load Grok consensus. Please retry.</p>
      )}

      {!loading && !error && data && (
        <div className="space-y-3">
          <FieldBlock label="Validation Summary" value={data.validationSummary} />
          <FieldBlock label="Structural Impact" value={data.structuralImpact} />
          <FieldBlock label="Consensus Assessment" value={data.consensusAssessment} />
        </div>
      )}

      {!loading && !error && !data && (
        <p className="text-slate-400 text-sm italic">No Grok consensus available for this variant.</p>
      )}

      <div className="mt-4 flex items-start gap-2 text-[11px] text-slate-400">
        <Info size={14} className="text-amber-400 shrink-0 mt-0.5" />
        <span>
          <strong className="text-amber-300 font-bold uppercase tracking-wide">Research Use Only:</strong>{' '}
          independent structural consensus generated by Grok — not a diagnosis.
        </span>
      </div>

      <GitCompare
        size={88}
        className="absolute -bottom-3 -right-3 text-cyan-500/10 pointer-events-none"
        aria-hidden="true"
      />
    </div>
  );
};

export default GrokConsensusCard;
